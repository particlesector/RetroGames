#!/usr/bin/env python3
"""Builds build/sprites.chr (4 KB) and build/sprites.inc.

The car is described once as a shape and rendered at nine angles (0 to 90 degrees);
the game mirrors those to get all 32 headings.
"""
import sys, os, math
import numpy as np

OUT = sys.argv[1]
SCALE = 1.22          # shrinks the car: the shape below is drawn for a 13-pixel car, this makes it about 11

def car(theta):
    """16x16 open-wheel racer: 0 clear, 1 dark (tyres, cockpit), 2 body colour, 3 white (wings, helmet)."""
    out = np.zeros((16, 16), int); c, s = math.cos(theta), math.sin(theta)
    for py in range(16):
        for px in range(16):
            votes = [0, 0, 0, 0]
            for sy in (0.125, 0.375, 0.625, 0.875):
                for sx in (0.125, 0.375, 0.625, 0.875):
                    dx, dy = (px + sx - 8) * SCALE, (py + sy - 8) * SCALE
                    x, y = dx * c + dy * s, -dx * s + dy * c; ay = abs(y)
                    k = 0
                    if (2.4 <= x <= 5.4 and 2.5 <= ay <= 4.3) or (-5.6 <= x <= -2.2 and 2.3 <= ay <= 4.6): k = 1
                    if (-5.2 <= x <= 3 and ay <= 1.7) or (3 < x <= 6.6 and ay <= 1.7 - (x - 3) * 0.33) \
                            or (-3.6 <= x <= 1.4 and ay <= 2.7): k = 2
                    if (-6.8 <= x <= -5.4 and ay <= 3.8) or (5.6 <= x <= 6.8 and ay <= 3.3): k = 3
                    if -1.3 <= x <= 1.3 and ay <= 1.0: k = 1
                    if -0.4 <= x <= 0.9 and ay <= 0.62: k = 3
                    votes[k] += 1
            if votes[0] < 9: out[py, px] = 1 + int(np.argmax(votes[1:]))
    return out

def enc(t):
    p0 = bytes(int(sum(((t[y][x] & 1) << (7 - x)) for x in range(8))) for y in range(8))
    p1 = bytes(int(sum(((t[y][x] >> 1) << (7 - x)) for x in range(8))) for y in range(8))
    return p0 + p1

tiles = [bytes(16)]; index = {bytes(16): 0}
def alloc(t):
    k = enc(t)
    if k not in index: index[k] = len(tiles); tiles.append(k)
    return index[k]
def art(rows, key): return [[key[c] for c in r] for r in rows]

frames = []
for i in range(9):
    c = car(i * math.pi / 16)
    frames.append([alloc(c[qy * 8:qy * 8 + 8, qx * 8:qx * 8 + 8].tolist()) for (qx, qy) in [(0, 0), (1, 0), (0, 1), (1, 1)]])

K = {".": 0, "k": 1, "c": 2, "w": 3}
SPR = {
 "SPR_RAIN": alloc(art([".......w", "......w.", ".....w..", "....w...", "...w....", "........", "........", "........"], K)),
 "SPR_SMOKE1": alloc(art(["........", "...ww...", "..w..w..", ".w....w.", ".w....w.", "..w..w..", "...ww...", "........"], K)),
 "SPR_SMOKE2": alloc(art(["..w..w..", "w......w", "........", "w......w", "........", "w......w", "........", "..w..w.."], K)),
 "SPR_SPRAY": alloc(art(["........", "..w.....", ".....w..", ".w......", "....w...", "......w.", "..w.....", "........"], K)),
 "SPR_ARROW": alloc(art(["...ww...", "..wwww..", ".wwwwww.", "wwwwwwww", "...ww...", "...ww...", "...ww...", "........"], K)),
 "SPR_P1": alloc(art(["..kkkk..", ".kkwwkk.", ".kwwwkk.", ".kkwwkk.", ".kkwwkk.", ".kwwwwk.", "..kkkk..", "........"], K)),
 "SPR_P2": alloc(art(["..kkkk..", ".kwwwkk.", ".kkkwwk.", ".kkwwkk.", ".kwwkkk.", ".kwwwwk.", "..kkkk..", "........"], K)),
 "SPR_DOT": alloc(art(["........", "........", "........", "...ww...", "...ww...", "........", "........", "........"], K)),
}
assert len(tiles) <= 256
open(f"{OUT}/sprites.chr", "wb").write(b"".join(tiles).ljust(4096, b"\0"))

# heading 0..31 -> base frame and mirror bits (bit 6 horizontal, bit 7 vertical)
hf, hm = [], []
for h in range(32):
    if h <= 8: f, m = h, 0
    elif h <= 16: f, m = 16 - h, 0x40
    elif h <= 24: f, m = h - 16, 0xC0
    else: f, m = 32 - h, 0x80
    hf.append(f * 4); hm.append(m)
with open(f"{OUT}/sprites.inc", "w") as f:
    f.write("; generated by tools/build_sprites.py\n")
    f.write("car_tiles: .byte " + ", ".join("$%02X" % t for fr in frames for t in fr) + "\n")
    f.write("heading_frame: .byte " + ", ".join(str(v) for v in hf) + "\n")
    f.write("heading_flip: .byte " + ", ".join("$%02X" % v for v in hm) + "\n")
    for k, v in SPR.items(): f.write(f"{k} = ${v:02X}\n")
    # trig: sin over a full turn of 256 steps, scaled to +-127; cos(a) = sin(a + 64)
    f.write("sin_tbl: .byte " + ", ".join(str(round(127 * math.sin(a * 2 * math.pi / 256)) & 255) for a in range(256)) + "\n")
    # quarter-square tables for fast 8x8 multiplication: f(n) = n*n/4 for n = 0..511
    sq = [(n * n) // 4 for n in range(512)]
    for name, lo, part in (("sq_lo", 0, 0), ("sq_hi", 8, 0), ("sq2_lo", 0, 256), ("sq2_hi", 8, 256)):
        f.write(f"{name}: .byte " + ", ".join(str((sq[part + n] >> lo) & 255) for n in range(256)) + "\n")
print(f"sprites: {len(tiles)} tiles")
