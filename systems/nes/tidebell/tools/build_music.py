#!/usr/bin/env python3
"""Compiles assets/music.txt into build/music.inc for src/sound.s.

Stream bytes: $00 rest, $01-$48 note (1 = C2), $80|n set length (ticks),
$C0|n instrument, $FE lo hi jump, $FF end.
"""
import sys, re

src, out = sys.argv[1], sys.argv[2]
NOTE = {"c": 0, "d": 2, "e": 4, "f": 5, "g": 7, "a": 9, "b": 11}
DRUM = {"k": (5, 13), "s": (5, 8), "h": (4, 3)}

def expand(text):
    while True:
        m = re.search(r"\{([^{}]*)\}x(\d+)", text)
        if not m: return text
        text = text[:m.start()] + (m.group(1) + " ") * int(m.group(2)) + text[m.end():]

def compile_stream(text, kind, label, loop):
    b, ticks, ln, cur_len, inst, loop_at = [], 0, 4, None, None, 0
    def emit(v, n):
        nonlocal cur_len, ticks
        if n != cur_len: b.append(0x80 | n); cur_len = n
        b.append(v); ticks += n
    for tok in expand(text).split():
        if tok == "|": continue
        if tok == "L": loop_at = len(b); cur_len = None; inst_reset = True; continue
        if tok[0] == "@": b.append(0xC0 | int(tok[1:])); inst = int(tok[1:]); continue
        if tok[0] == "l" and tok[1:].isdigit(): ln = int(tok[1:]); continue
        name, _, n = tok.partition(":"); n = int(n) if n else ln
        assert 1 <= n <= 63, tok
        if name == "r": emit(0, n); continue
        if kind == "N":
            if name in DRUM:
                i, v = DRUM[name]
                if inst != i: b.append(0xC0 | i); inst = i
                emit(v, n)
            else:
                assert name[0] == "n", tok; emit(int(name[1:]) + 1, n)
            continue
        m = re.fullmatch(r"([a-g])(#?)(\d)", name); assert m, f"bad token {tok!r} in {label}"
        v = NOTE[m.group(1)] + (1 if m.group(2) else 0) + (int(m.group(3)) - 2) * 12 + 1
        if kind == "T": v += 12
        assert 1 <= v <= 72, tok
        emit(v, n)
    if loop: b += [0xFE, ("jmp", loop_at)]
    else: b.append(0xFF)
    return b, ticks

songs, sfx, cur = [], [], None
for line in open(src):
    line = line.split(";")[0].strip()
    if not line: continue
    w = line.split()
    if w[0] in ("song", "sfx"):
        cur = {"name": w[1], "speed": 6, "loop": w[0] == "song", "ch": {}}
        for a in w[2:]:
            if a.startswith("speed="): cur["speed"] = int(a[6:])
            if a == "noloop": cur["loop"] = False
        (songs if w[0] == "song" else sfx).append(cur)
    else:
        ch, _, body = line.partition(":")
        cur["ch"][ch.strip()] = cur["ch"].get(ch.strip(), "") + " " + body

L = ["; generated by tools/build_music.py"]
def dump(label, b):
    parts = []
    for x in b:
        if isinstance(x, tuple): parts += [f"<({label}+{x[1]})", f">({label}+{x[1]})"]
        else: parts.append("$%02X" % x)
    L.append(f"{label}: .byte " + ", ".join(parts))
table = []
for i, s in enumerate(songs):
    L.append(f"SONG_{s['name'].upper()} = {i}")
    row, tk = [], {}
    for ch, kind in (("P1", "P"), ("P2", "P"), ("TR", "T"), ("NO", "N")):
        if ch in s["ch"]:
            lab = f"mus_{s['name']}_{ch}"
            b, tk[ch] = compile_stream(s["ch"][ch], kind, lab, s["loop"]); dump(lab, b); row.append(lab)
        else: row.append("0")
    assert len(set(tk.values())) == 1, f"song {s['name']}: channel lengths differ {tk}"
    table.append(row)
L.append("song_table: .word " + ", ".join(x for r in table for x in r))
L.append("song_speed: .byte " + ", ".join(str(s["speed"]) for s in songs))
table = []
for i, s in enumerate(sfx):
    L.append(f"SFX_{s['name'].upper()} = {i}")
    row = []
    for ch, kind in (("P", "P"), ("N", "N")):
        if ch in s["ch"]:
            lab = f"sfx_{s['name']}_{ch}"
            b, _ = compile_stream(s["ch"][ch], kind, lab, False); dump(lab, b); row.append(lab)
        else: row.append("0")
    table.append(row)
L.append("sfx_table: .word " + ", ".join(x for r in table for x in r))
per = [0] + [round(1789773 / (16 * 440 * 2 ** ((36 + n - 69) / 12)) - 1) for n in range(72)]
L.append("per_lo: .byte " + ", ".join(str(p & 255) for p in per))
L.append("per_hi: .byte " + ", ".join(str(p >> 8) for p in per))
open(out, "w").write("\n".join(L) + "\n")
print(f"music: {len(songs)} songs, {len(sfx)} sfx")
