#!/usr/bin/env python3
"""Compiles assets/levels.txt into build/levels.inc.

Map characters:  . air   # rock   : sand   = dock   I post   ^ urchin   X crate
                 % coral (solid only under water)   S sandcastle (solid only in air)
                 D beacon door (lamp is placed above it)
Objects:         P Pim   e ember   c crab   j jellyfish   r raft (2 cells wide, mark the left one)
Scene-only:      A a roof   T t lamp   L l red band   W w white band   i window   O big door
                 1 2 3 beam   M moon (top-left of a 2x2)
"""
import sys, re, random, importlib.util

src, build = sys.argv[1], sys.argv[2]
spec = importlib.util.spec_from_file_location("gfx", f"{build}/gfx.py"); gfx = importlib.util.module_from_spec(spec); spec.loader.exec_module(gfx)
MT = gfx.MT
def h(x, y, s=0): return ((x * 73856093) ^ (y * 19349663) ^ (s * 83492791)) >> 3 & 0xFF

PLAIN = {"=": "DOCK", "I": "POST", "^": "URCHIN", "%": "CORAL", "X": "CRATE", "S": "CASTLE", "D": "DOOR",
         "A": "ROOF_L", "a": "ROOF_R", "T": "BLAMP_L", "t": "BLAMP_R", "L": "RED_L", "l": "RED_R",
         "W": "WHITE_L", "w": "WHITE_R", "i": "WIN_R", "O": "BIGDOOR", "1": "BEAM1", "2": "BEAM2", "3": "BEAM3"}
OBJ = {"e": 1, "c": 2, "j": 3, "r": 4}

rooms, cur = [], None
for ln, line in enumerate(open(src), 1):
    line = line.rstrip("\n")
    if line.startswith(";") or line.startswith("solve:") or not line.strip(): continue
    m = re.match(r'(room|scene)\s+(?:"([^"]*)"|(\w+))\s*(.*)', line)
    if m:
        cur = {"kind": m.group(1), "name": m.group(2) or m.group(3), "rows": [], "tide": [212, 180, 148],
               "start": 0, "storm": False, "pal": None, "line": ln}
        rest = m.group(4)
        hm = re.search(r'hint="([^"]*)"', rest)
        cur["hint"] = hm.group(1) if hm else ""
        assert len(cur["hint"]) <= 24, f"levels.txt:{ln}: hint longer than 24"
        if hm: rest = rest.replace(hm.group(0), "")
        for a in rest.split():
            if a.startswith("tide="): cur["tide"] = [int(v) for v in a[5:].split(",")]
            elif a.startswith("start="): cur["start"] = int(a[6:])
            elif a.startswith("pal="): cur["pal"] = int(a[4:])
            elif a == "storm": cur["storm"] = True
            else: sys.exit(f"levels.txt:{ln}: unknown option {a}")
        rooms.append(cur)
    else:
        assert len(line) == 16, f"levels.txt:{ln}: row must be 16 wide, got {len(line)}"
        cur["rows"].append(line)

game = [r for r in rooms if r["kind"] == "room"]
scenes = [r for r in rooms if r["kind"] == "scene"]
out = ["; generated by tools/build_levels.py", f"NUM_ROOMS = {len(game)}"]
for i, s in enumerate(scenes): out.append(f"SCENE_{s['name'].upper()} = {len(game) + i}")

for n, r in enumerate(game + scenes):
    rows, where = r["rows"], f"levels.txt:{r['line']} ({r['name']})"
    assert len(rows) == 13, f"{where}: need 13 rows, got {len(rows)}"
    assert len(r["tide"]) == 3 and r["tide"][0] >= r["tide"][1] >= r["tide"][2], f"{where}: tide must be low,mid,high"
    g = lambda x, y: rows[y][x] if 0 <= y < 13 and 0 <= x < 16 else "."
    cells, objs, pim, used = [[0] * 16 for _ in range(13)], [], None, set()
    for y in range(13):
        for x in range(16):
            c = g(x, y)
            if c == "#": name = "ROCK" if g(x, y - 1) == "#" else "ROCKTOP"
            elif c == ":": name = "SAND" if g(x, y - 1) in ":#" else "SANDTOP"
            elif c == "=": name = "DOCKPOST" if g(x, y + 1) == "I" else "DOCK"
            elif c in PLAIN: name = PLAIN[c]
            elif c == "P": pim = (x * 16, (y + 2) * 16); name = None
            elif c in OBJ:
                t = OBJ[c]
                if t == 1: objs.append((1, x * 16 + 4, (y + 2) * 16 + 6))
                elif t == 4:
                    if g(x - 1, y) != "r" or (x - 1, y) not in used:
                        objs.append((4, x * 16, (y + 2) * 16)); used.add((x, y))
                else: objs.append((t, x * 16, (y + 2) * 16))
                name = None
            elif c == "M":
                for k, (dx, dy) in enumerate([(0, 0), (1, 0), (0, 1), (1, 1)]): cells[y + dy][x + dx] = MT["MOON%d" % k]
                continue
            elif c == ".": name = None
            else: sys.exit(f"{where}: unknown map character {c!r}")
            if name: cells[y][x] = MT[name]
            if c == "D":
                assert y > 0 and g(x, y - 1) == ".", f"{where}: door needs air above"
                cells[y - 1][x] = MT["LAMP"]
    busy = {(o[1] // 16, o[2] // 16 - 2) for o in objs} | ({(pim[0] // 16, pim[1] // 16 - 2)} if pim else set())
    if r["kind"] == "room":
        assert pim, f"{where}: no P"
        assert sum(row.count("D") for row in rows) == 1, f"{where}: need exactly one D"
        ne = sum(1 for o in objs if o[0] == 1)
        assert 1 <= ne <= 4, f"{where}: need 1-4 embers"
        assert len(objs) - ne <= 8, f"{where}: too many objects"
        top = r["tide"][2] // 16 - 2          # first row the high tide touches
        spots = [(x, y) for y in range(1 if r["hint"] else 0, 3) for x in range(1, 14)
                 if y + 1 < top and all(cells[y + dy][x + dx] == 0 and (x + dx, y + dy) not in busy
                                        for dx in (0, 1) for dy in (0, 1))]
        if spots:
            x, y = spots[h(n, 7, 3) % len(spots)]
            for k, (dx, dy) in enumerate([(0, 0), (1, 0), (0, 1), (1, 1)]): cells[y + dy][x + dx] = MT["MOON%d" % k]
    srng = random.Random(n * 7 + 1)
    for y in range(9):
        for x in range(16):
            if cells[y][x] == 0 and (x, y) not in busy and srng.random() < 0.16:
                cells[y][x] = MT["STAR1"] + srng.randrange(2)
    pal = r["pal"] if r["pal"] is not None else min(n // 8, 4)
    flags = r["start"] | (0x80 if r["storm"] else 0)
    px, py = pim if pim else (0, 0)
    out.append(f"room_{n}:  ; {r['name']}")
    out.append(f"  .byte {r['tide'][0]}, {r['tide'][1]}, {r['tide'][2]}, ${flags:02X}, {px}, {py}, {pal}")
    out.append(f'  .byte "{r["name"].upper() if r["kind"] == "room" else ""}", $FF, "{r["hint"]}", $FF')
    for row in cells: out.append("  .byte " + ", ".join(str(v) for v in row))
    out.append("  .byte " + "".join(f"{t}, {x}, {y}, " for t, x, y in objs) + "$FF")
out.append("room_lo: .byte " + ", ".join(f"<room_{i}" for i in range(len(rooms))))
out.append("room_hi: .byte " + ", ".join(f">room_{i}" for i in range(len(rooms))))
rng, seen, pw = random.Random(1987), set(), []
while len(pw) < len(game):
    w = "".join(rng.choice("BDFGHJKLMNPRSTVWZ") + rng.choice("AEIOU") for _ in range(2))
    if w not in seen: seen.add(w); pw.append(w)
out.append("passwords: .byte " + ", ".join(str(ord(c) - 65) for w in pw for c in w))
open(f"{build}/levels.inc", "w").write("\n".join(out) + "\n")
open(f"{build}/passwords.txt", "w").write("".join(f"{i // 8 + 1}-{i % 8 + 1} {w}\n" for i, w in enumerate(pw)))
print(f"levels: {len(game)} rooms, {len(scenes)} scenes")
